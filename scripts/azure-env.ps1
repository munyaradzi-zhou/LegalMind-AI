<#
.SYNOPSIS
    Load the endpoints of a deployed LegalMind environment into this PowerShell session
    (and write them to .env.azure), for running the evaluations, the API or the MCP
    server locally against Azure with your own `az login` identity. No keys involved.
    Endpoints are read from the resources themselves, so this works even while (or after)
    a deployment is running, cancelled or failed.

.EXAMPLE
    . .\scripts\azure-env.ps1          # note the leading dot: loads the variables into this session
    . .\scripts\azure-env.ps1 staging
#>
param([string]$Environment = "dev")

$ErrorActionPreference = "Stop"
$rg = "rg-legalmind-$Environment"

$search = az search service list -g $rg --query "[0].name" -o tsv
if (-not $search) { throw "No LegalMind resources found in $rg." }

$ai = az cognitiveservices account list -g $rg -o json | ConvertFrom-Json
function Get-AiEndpoint([scriptblock]$Match) { ($ai | Where-Object $Match | Select-Object -First 1).properties.endpoint }
function Get-AppUrl([string]$Name) { "https://" + (az containerapp show -g $rg -n $Name --query properties.configuration.ingress.fqdn -o tsv) }

$vars = [ordered]@{
    LLM_PROVIDER                         = "azure"
    AZURE_OPENAI_ENDPOINT                = Get-AiEndpoint { $_.kind -eq "OpenAI" }
    AZURE_OPENAI_CHAT_DEPLOYMENT         = "gpt-4.1-mini"
    AZURE_OPENAI_EMBEDDING_DEPLOYMENT    = "text-embedding-3-large"
    AZURE_SEARCH_ENDPOINT                = "https://$search.search.windows.net"
    AZURE_LANGUAGE_ENDPOINT              = Get-AiEndpoint { $_.name -like "ais-*" }
    AZURE_DOCUMENT_INTELLIGENCE_ENDPOINT = Get-AiEndpoint { $_.kind -eq "FormRecognizer" }
    AZURE_CONTENT_UNDERSTANDING_ENDPOINT = Get-AiEndpoint { $_.name -like "cu-*" }
    AZURE_CONTENT_SAFETY_ENDPOINT        = Get-AiEndpoint { $_.kind -eq "ContentSafety" }
    AZURE_COSMOS_ENDPOINT                = az cosmosdb list -g $rg --query "[0].documentEndpoint" -o tsv
    AZURE_STORAGE_ACCOUNT_URL            = az storage account list -g $rg --query "[0].primaryEndpoints.blob" -o tsv
    API_URL                              = Get-AppUrl "ca-legalmind-api-$Environment"
    WEB_URL                              = Get-AppUrl "ca-legalmind-web-$Environment"
}

$lines = @("# Generated by scripts/azure-env.ps1 for $rg - endpoints only, no secrets.")
foreach ($name in $vars.Keys) {
    Set-Item -Path "Env:$name" -Value $vars[$name]
    $lines += "$name=$($vars[$name])"
}
$file = Join-Path (Split-Path $PSScriptRoot -Parent) ".env.azure"
[IO.File]::WriteAllLines($file, $lines)   # UTF-8 without BOM

Write-Host "Loaded $($vars.Count) variables into this session and wrote $file"
Write-Host "API_URL = $env:API_URL"
