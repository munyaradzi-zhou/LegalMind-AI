#!/usr/bin/env bash
# Write .env.azure: the endpoints of a deployed environment, for running the API,
# the evaluations or the MCP server on your machine against Azure.
# Uses your own `az login` identity (DefaultAzureCredential) — no keys involved.
# Endpoints are read from the resources themselves, so this works even while (or after)
# a deployment is running, cancelled or failed.
#
#   bash scripts/azure-env.sh [environment]        # default: dev
#   set -a; source .env.azure; set +a              # load into the current shell
set -euo pipefail

ENVIRONMENT="${1:-dev}"
RG="rg-legalmind-${ENVIRONMENT}"
ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
OUT="${ROOT}/.env.azure"

ai() { az cognitiveservices account list -g "${RG}" --query "[?$1].properties.endpoint | [0]" -o tsv; }
app() { echo "https://$(az containerapp show -g "${RG}" -n "$1" --query properties.configuration.ingress.fqdn -o tsv)"; }

SEARCH=$(az search service list -g "${RG}" --query "[0].name" -o tsv)
[[ -n "${SEARCH}" ]] || { echo "No LegalMind resources found in ${RG}." >&2; exit 1; }

cat > "${OUT}" << VARS
# Generated by scripts/azure-env.sh for ${RG} — endpoints only, no secrets.
LLM_PROVIDER=azure
AZURE_OPENAI_ENDPOINT=$(ai "kind=='OpenAI'")
AZURE_OPENAI_CHAT_DEPLOYMENT=gpt-4.1-mini
AZURE_OPENAI_EMBEDDING_DEPLOYMENT=text-embedding-3-large
AZURE_SEARCH_ENDPOINT=https://${SEARCH}.search.windows.net
AZURE_LANGUAGE_ENDPOINT=$(ai "starts_with(name,'ais-')")
AZURE_DOCUMENT_INTELLIGENCE_ENDPOINT=$(ai "kind=='FormRecognizer'")
AZURE_CONTENT_UNDERSTANDING_ENDPOINT=$(ai "starts_with(name,'cu-')")
AZURE_CONTENT_SAFETY_ENDPOINT=$(ai "kind=='ContentSafety'")
AZURE_COSMOS_ENDPOINT=$(az cosmosdb list -g "${RG}" --query "[0].documentEndpoint" -o tsv)
AZURE_STORAGE_ACCOUNT_URL=$(az storage account list -g "${RG}" --query "[0].primaryEndpoints.blob" -o tsv)
API_URL=$(app "ca-legalmind-api-${ENVIRONMENT}")
WEB_URL=$(app "ca-legalmind-web-${ENVIRONMENT}")
VARS
echo "Wrote ${OUT}"
